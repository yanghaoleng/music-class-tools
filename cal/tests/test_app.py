  r=admin.post('/cal/api/access',json={'role':'teacher','person':t['id']}).get_json();a=m.app.test_client()
  self.assertEqual(a.post('/cal/api/login',json={'code':r['code']}).status_code,200)
  admin.post('/cal/api/access',json={'role':'teacher','person':t['id']})
  self.assertEqual(a.get('/cal/api/bootstrap').status_code,401)
  self.assertEqual(a.post('/cal/api/login',json={'code':r['code']}).status_code,401)
