 def test_drag_moves_one_lesson_without_changing_metadata(self):
  self.assertEqual(self.lesson(feedback='保留课堂反馈',parentFeedback='保留家长反馈').status_code,200)
  before=self.get();lesson=next(l for l in before['lessons'] if l['date']==self.day)
  target=(m.today()+timedelta(days=10)).isoformat()
  payload=dict(id=lesson['id'],date=target,time='15:15',expected_date=lesson['date'],expected_time=lesson['time'])
  self.assertEqual(self.post('lessons/move',payload).status_code,200)
  after=self.get();moved=next(l for l in after['lessons'] if l['id']==lesson['id'])
  self.assertEqual(moved,dict(lesson,date=target,time='15:15'))
  self.assertEqual(len(after['lessons']),len(before['lessons']))
  self.assertEqual(after['students'],before['students'])
  self.assertEqual(self.post('lessons/move',dict(payload,time='18:00')).status_code,409)
 def test_drag_conflict_rollback_and_invalid_destination(self):
  self.lesson();self.lesson(student='s2',time='17:00',room='B')
  lesson=next(l for l in self.get()['lessons'] if l['date']==self.day and l['student']=='s1')
  payload=dict(id=lesson['id'],date=self.day,time='17:00',expected_date=lesson['date'],expected_time=lesson['time'])
  self.assertEqual(self.post('lessons/move',payload).status_code,400)
  self.assertEqual(next(l for l in self.get()['lessons'] if l['id']==lesson['id']),lesson)
  self.assertEqual(self.post('lessons/move',dict(payload,time='20:30')).status_code,400)
  self.assertEqual(self.post('lessons/move',dict(payload,date=(m.today()-timedelta(days=1)).isoformat())).status_code,400)
  teacher=self.get()['teachers'][0];off=(m.today()+timedelta(days=11)).isoformat()
  self.post('people',dict(teacher,kind='teachers',offDates=[off]))
  self.assertEqual(self.post('lessons/move',dict(payload,date=off)).status_code,400)
 def test_drag_permissions_completed_and_cross_tenant(self):
  self.lesson();lesson=next(l for l in self.get()['lessons'] if l['date']==self.day)
  payload=dict(id=lesson['id'],date=self.day,time='18:00',expected_date=lesson['date'],expected_time=lesson['time'])
  for role in ['student','parent']:
   self.post('demo-role',dict(role=role));self.assertEqual(self.post('lessons/move',payload).status_code,403)
  self.post('demo-role',dict(role='admin'))
  self.assertEqual(self.lesson(teacher='t3',student='s4',time='18:00',room='B').status_code,200)
  foreign=next(l for l in self.get()['lessons'] if l['date']==self.day and l['teacher']=='t3')
  self.post('demo-role',dict(role='teacher'));self.assertEqual(self.post('lessons/move',dict(payload,id=foreign['id'],expected_time='18:00')).status_code,403)
  self.assertEqual(self.post('lessons/move',payload).status_code,200)
  completed=next(l for l in self.get()['lessons'] if l['status']=='completed')
  self.assertEqual(self.post('lessons/move',dict(payload,id=completed['id'],expected_date=completed['date'],expected_time=completed['time'])).status_code,409)
  other=m.app.test_client();other.post('/cal/api/demo',json={})
  self.assertEqual(other.post('/cal/api/lessons/move',json=payload).status_code,404)
 def test_real_login_revocation_no_role_escalation(self):
  admin=m.app.test_client();code=(m.DATA/'admin-access.txt').read_text().split('管理口令：')[1].splitlines()[0]
  self.assertEqual(admin.post('/cal/api/login',json={'code':code}).status_code,200)
