import os,tempfile,unittest,sys,json
from datetime import timedelta
os.environ['CAL_DATA']=tempfile.mkdtemp(prefix='music-cal-tests-')
sys.path.insert(0,os.path.dirname(os.path.dirname(__file__)))
import server as m

class Scheduling(unittest.TestCase):
 def setUp(self):
  self.c=m.app.test_client(); self.c.post('/cal/api/demo',json={})
  self.day=(m.today()+timedelta(days=9)).isoformat()
 def get(self): return self.c.get('/cal/api/bootstrap').get_json()
 def post(self,path,p): return self.c.post('/cal/api/'+path,json=p)
 def lesson(self,**kw):
  p=dict(teacher='t1',student='s1',date=self.day,time='16:00',room='Room A');p.update(kw);return self.post('lessons',p)
 def rules(self,**kw):
  s=dict(teacher='t1',students=['s1','s2'],start_date=self.day,end_date=self.day,weekdays=[1,2,3,4,5,6,7],start_time='14:00',end_time='18:00',count=1,excluded_dates=[],room='');s.update(kw)
  return dict(start=self.day,end=self.day,rules={'summary':'test','series':[s]})
 def test_teacher_student_room_break_and_cancel(self):
  self.assertEqual(self.lesson().status_code,200)
  self.assertEqual(self.lesson(student='s2',time='16:50').status_code,400)
  self.assertEqual(self.lesson(teacher='t2',student='s1',room='B',time='16:30').status_code,400)
  self.assertEqual(self.lesson(teacher='t2',student='s3',time='16:30').status_code,400)
  self.assertEqual(self.lesson(student='s2',time='17:00').status_code,200)
  l=next(x for x in self.get()['lessons'] if x['date']==self.day and x['time']=='16:00')
  self.assertEqual(self.post('lessons',dict(id=l['id'],status='cancelled')).status_code,200)
  self.assertEqual(self.lesson(time='16:00').status_code,200)
 def test_atomic_stale_proposal_and_double_apply(self):
  p=self.post('preview',self.rules()).get_json();self.assertEqual(len(p['items']),2)
  self.lesson(time='10:00')
  self.assertEqual(self.post('apply',{'id':p['id']}).status_code,409)
  p=self.post('preview',self.rules()).get_json()
  self.assertEqual(self.post('apply',{'id':p['id']}).status_code,200)
  self.assertEqual(self.post('apply',{'id':p['id']}).status_code,409)
  self.assertEqual(len([x for x in self.get()['lessons'] if x['date']==self.day]),3)
 def test_roles_and_private_fields(self):
  self.post('demo-role',{'role':'student'});d=self.get()
  self.assertEqual(len(d['students']),1);self.assertNotIn('credits',d['students'][0]);self.assertNotIn('parentNote',d['students'][0])
  self.assertTrue(all(l['student']=='s1' and 'parentFeedback' not in l for l in d['lessons']))
  self.assertEqual(self.lesson().status_code,403)
  self.assertEqual(self.post('people',{'kind':'teachers'}).status_code,403)
  self.post('demo-role',{'role':'parent'});d=self.get();self.assertIn('credits',d['students'][0])
  self.post('demo-role',{'role':'teacher'});d=self.get();self.assertTrue(all(l['teacher']=='t1' for l in d['lessons']))
  self.assertEqual(self.lesson(teacher='t2').status_code,403)
  self.assertEqual(self.post('preview',self.rules(teacher='t2',students=['s3'])).status_code,403)
 def test_requests_confirm_and_conflict(self):
  self.post('demo-role',{'role':'student'})
  p=dict(teacher='t1',date=self.day,time='15:00')
  self.assertEqual(self.post('requests',p).status_code,200)
  self.assertEqual(self.post('requests',p).status_code,400)
  req=self.get()['requests'][0];self.assertFalse(any(x['date']==self.day for x in self.get()['lessons']))
  self.post('demo-role',{'role':'admin'});self.lesson(student='s2',time='15:00',room='')
  self.assertEqual(self.post('requests/resolve',{'id':req['id'],'accept':True}).status_code,400)
  self.assertEqual(self.post('requests/resolve',{'id':req['id'],'accept':False}).status_code,200)
  self.post('demo-role',{'role':'student'});self.assertEqual(self.post('requests',{**p,'time':'17:00'}).status_code,200)
  req=self.get()['requests'][-1];self.post('demo-role',{'role':'teacher'})
  self.assertEqual(self.post('requests/resolve',{'id':req['id'],'accept':True}).status_code,200)
  self.assertEqual(self.post('requests/resolve',{'id':req['id'],'accept':True}).status_code,409)
 def test_off_days_and_credit_limits(self):
  d=self.get();t=d['teachers'][0]
  self.assertEqual(self.post('people',dict(t,kind='teachers',offDates=[self.day])).status_code,200)
  self.assertEqual(self.lesson().status_code,400)
  p=self.post('preview',self.rules()).get_json();self.assertEqual(p['items'],[]);self.assertTrue(p['skipped'])
